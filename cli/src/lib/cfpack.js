// The Cloudflare target: a manifest becomes a Worker that is an agent.
//
// `epito deploy` has had one target since it landed — a GitHub App, which is
// the agent's identity and nothing else. The owner asked for the other half on
// a runtime nobody has to keep alive: take one of our manifests and produce an
// agent on Cloudflare with its own identity, a schedule that fires, state that
// survives, and a page showing the agent, its last run and a button.
//
// Everything in this file is PURE. It reads a manifest and returns the bytes
// of a deployable bundle; it touches no network, no browser and no account.
// The one command that is not ours to run is `wrangler deploy`, which belongs
// to whoever holds the Cloudflare account — epito writes what it would deploy
// and says so, the same way `epito deploy --dry-run` does for GitHub.
//
// WHAT IS NOT HERE, on purpose:
//
//   a new manifest field. Not one. The four things the ask names all have an
//   answer already in the file — [identity].scopes is the App, [trigger].cron
//   is the schedule, [runtime].repo + entry is what the run reads, and the
//   state is the runtime's business, not the manifest's. If a second deploy
//   target had needed a field, that would have been a finding about the spec
//   (the manifest was supposed to be portable); it needed none, which is the
//   strongest evidence the freeze has had.
//
//   any secret VALUE, in any generated file. Rule 1 is a property of the
//   manifest, and a bundle generated from a manifest inherits it: the
//   wrangler config and the worker name secrets, and the operator puts the
//   values in with `wrangler secret put`. The test suite asserts it by
//   scanning every generated byte.
import { readFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { permissionsFor } from "./identity.js";
import { routesFor } from "./router.js";
import { parseCron } from "./cron.js";
import { SPEC_VERSION } from "./fields.js";

// The worker's source lives in the package as a real file rather than as a
// string in this one: it is 400 lines of runtime code, and code that is only
// ever a template string is code nobody reads, lints or imports in a test.
// The test suite imports it out of a bundle it generated, which is the only
// way to assert that the thing shipped is the thing tested.
const HERE = dirname(fileURLToPath(import.meta.url));
export const WORKER_SOURCE = resolve(HERE, "..", "cloudflare", "worker.mjs");

// Worker names are [a-z0-9-], up to 63 characters, and globally unique only
// within the account — so unlike a GitHub App name this needs no owner suffix.
// The prefix exists so an account that runs other Workers can see at a glance
// which ones epito put there.
export const workerName = (agentName) => `epito-${agentName}`.slice(0, 63);

// The default place a bundle lands: inside .epito/, which is already
// gitignored and already where this product keeps per-agent machinery.
export const bundleDir = (agentName) => join(".epito", "cloudflare", agentName);

// Pinned, not "today". A compatibility date is the Workers runtime's version,
// and generating a different one on every run would mean the same manifest
// deployed twice is two different runtimes — the opposite of rule 4. Bump it
// deliberately, in a diff.
export const COMPATIBILITY_DATE = "2026-10-01";

// The binding names the worker reads. One list, here, because the worker and
// the config it is deployed with cannot be allowed to disagree about them.
export const BINDINGS = {
  state: "RUNS",
  doClass: "AgentRuns",
  // The one door, and the one secret behind it. Same shape as the resident
  // runtime's ingress (x-epito-secret), so an operator who has met one has
  // met both.
  door: "EPITO_TRIGGER_SECRET",
  appId: "EPITO_APP_ID",
  appKey: "EPITO_APP_KEY",
  // The edge's floor. On a box, a seat with a route that names no token_env
  // runs on the operator's Claude subscription; a Worker cannot hold a
  // subscription, so the bottom road on Cloudflare is an API key under this
  // name. Named here rather than invented in the worker so the deploy output,
  // the README and the runtime all say the same word.
  modelKey: "ANTHROPIC_API_KEY",
};

// --- what Cloudflare cannot do with this manifest -------------------------

// Refusals, in the product's voice: the rule broken, in the manifest's own
// vocabulary, with the fix in the message. These run BEFORE anything is
// written, because a half-written bundle an operator then deploys is worse
// than no bundle.
export function cloudflareBlockers(manifest, path = "agent.toml") {
  const out = [];
  const rt = manifest?.runtime ?? {};
  const name = manifest?.agent?.name ?? "this agent";

  if (!rt.repo) {
    out.push(`[runtime].repo is required to deploy "${name}" to Cloudflare: the Worker reads this seat's charter out of its repository on every run, with the seat's own token, so a manifest with no repository describes a run with nothing to read. Fix: add repo = "owner/name" to [runtime] in ${path}.`);
  }
  if (rt.adapter && rt.adapter !== "claude") {
    out.push(`[runtime].adapter = "${rt.adapter}" cannot run on Cloudflare: an adapter is a process epito spawns, and a Worker spawns no processes — there is no interpreter, no virtualenv and no filesystem to install one into. Fix: deploy this seat to the resident runtime (\`epito run <dir>\`), which is where a non-Claude adapter runs, or drop the field to run it as a Claude seat on the edge.`);
  }
  if (rt.graph) {
    out.push(`[runtime].graph names a graph in a LangGraph app, and a LangGraph app cannot run on Cloudflare (see the adapter line above). Fix: deploy this seat to the resident runtime.`);
  }
  if (!manifest?.trigger?.cron && !manifest?.trigger?.webhook) {
    out.push(`"${name}" declares no trigger, so a Worker made of it would never wake: [trigger].cron becomes the Worker's schedule and [trigger].webhook is what lets the page's button fire it. Fix: add cron = "0 6 * * *" or webhook = true to [trigger] in ${path}.`);
  }
  if (manifest?.trigger?.cron) {
    // Cloudflare's cron is the same five UTC fields `epito run` registers, so
    // what `epito validate` already parsed is what Cloudflare will take. The
    // one thing worth re-checking here is a manifest that reached deploy
    // without validate: a schedule Cloudflare refuses is an error at
    // `wrangler deploy` time, long after this command said it was done.
    try { parseCron(manifest.trigger.cron); }
    catch (e) {
      out.push(`[trigger].cron = "${manifest.trigger.cron}" is not a schedule (${e.message}), and it is copied verbatim into the Worker's own triggers — Cloudflare would refuse it at deploy time, after this command had already said the bundle was ready. Fix: correct the expression in ${path}; \`epito validate\` checks it too.`);
    }
  }
  try { permissionsFor(manifest?.identity?.scopes ?? []); }
  catch (e) { out.push(e.message); }
  return out;
}

// Not a refusal: a thing the operator is owed before they deploy, because the
// edge runtime is honestly smaller than the resident one and a silent
// downgrade is the failure mode this product exists to refuse.
export function cloudflareNotes(manifest) {
  const out = [];
  const rt = manifest?.runtime ?? {};
  const turns = rt.max_turns ?? 100;
  if (turns > 1) {
    out.push(`[runtime].max_turns is ${turns}, and an edge run is ONE turn: the Worker mints this seat's token, reads its charter out of ${rt.repo ?? "its repository"}, asks the model once, and records the answer. It does not clone, it does not commit and it does not open a pull request — a Worker has no git and no disk. The page says so on every run, rather than letting a one-turn run read as a ${turns}-turn seat.`);
  }
  if (!manifest?.trigger?.cron) {
    out.push(`"${manifest?.agent?.name}" has no [trigger].cron, so this Worker gets no schedule — it wakes only when someone presses the button on its page. That is a complete seat (webhook = true says the ingress may wake it) and it is worth knowing before you wait for 06:00.`);
  }
  if (!manifest?.trigger?.webhook) {
    out.push(`"${manifest?.agent?.name}" does not declare [trigger].webhook, so the page's button is OFF: a seat that did not ask to be woken by hand is not woken by hand (spec rule 3 — explicit beats defaulted). The page shows the agent and its runs and says why the button is missing. Fix, if you want the button: webhook = true under [trigger].`);
  }
  const chain = routesFor(manifest);
  const floor = chain.filter((r) => !r.tokenEnv);
  if (floor.length) {
    out.push(`${floor.length === 1 ? `the road "${floor[0].name}" names` : `${floor.length} roads name`} no token_env, which on a box means the operator's Claude subscription. A Worker cannot hold a subscription, so on the edge ${floor.length === 1 ? "that road runs" : "those roads run"} on $${BINDINGS.modelKey} — one more secret to set, and the reason it exists.`);
  }
  return out;
}

// --- the bundle -----------------------------------------------------------

// Every secret this Worker needs, by NAME, in the order an operator sets them.
// Derived from the manifest, so a seat that declares a gateway key is told
// about its gateway key and a seat that does not, is not.
export function secretNames(manifest) {
  const names = [
    { name: BINDINGS.door, why: "the one door: every request to this agent's page carries it, as ?key= in the link or x-epito-secret in a header" },
    { name: BINDINGS.appId, why: `this agent's GitHub App id — its own identity, the same App \`epito deploy\` creates` },
    { name: BINDINGS.appKey, why: `its App private key, in PKCS#8 (\`epito deploy --target cloudflare\` writes the converted copy; Workers' WebCrypto reads no other form)` },
  ];
  const chain = routesFor(manifest);
  if (chain.some((r) => !r.tokenEnv)) {
    names.push({ name: BINDINGS.modelKey, why: "the model key for the road that names none — the edge's floor, where a box would use the subscription" });
  }
  for (const r of chain) {
    if (r.tokenEnv) names.push({ name: r.tokenEnv, why: `the key for the road "${r.name}"` });
    if (r.baseUrlEnv) names.push({ name: r.baseUrlEnv, why: `the endpoint for the road "${r.name}", which the manifest holds as a name because the address itself is confidential` });
  }
  // A seat may list the same name twice (two roads, one key). Set it once.
  const seen = new Set();
  return names.filter((n) => (seen.has(n.name) ? false : seen.add(n.name)));
}

// The Workers config. Plain JSON on purpose, in a .jsonc file: wrangler reads
// both, every explanation belongs in the bundle's README where a person will
// find it, and a config that parses with JSON.parse is a config a test can
// assert on field by field instead of by regex.
export function wranglerConfig(manifest, { compatibilityDate = COMPATIBILITY_DATE } = {}) {
  const name = manifest.agent.name;
  const config = {
    $schema: "node_modules/wrangler/config-schema.json",
    name: workerName(name),
    main: "worker.mjs",
    compatibility_date: compatibilityDate,
    // Observability on: the owner's first question about a run that did not
    // happen is "did it even fire", and the Workers log is where that is
    // answered. Off by default on Cloudflare's side.
    observability: { enabled: true },
    durable_objects: {
      bindings: [{ name: BINDINGS.state, class_name: BINDINGS.doClass }],
    },
    // The state that survives. One Durable Object per agent, addressed by the
    // agent's name — which is spec rule 4 (one manifest, one principal) read
    // onto storage: deploying the same manifest twice keeps the run history,
    // and renaming the agent starts a new one, exactly as it starts a new
    // identity.
    migrations: [{ tag: "v1", new_sqlite_classes: [BINDINGS.doClass] }],
  };
  if (manifest.trigger?.cron) {
    // Verbatim. Cloudflare's cron is the same five UTC fields the manifest
    // wrote and `epito run` registers, so there is nothing to translate — and
    // a translation layer between a manifest and a schedule is exactly where
    // "it ran at the wrong hour" comes from.
    config.triggers = { crons: [manifest.trigger.cron] };
  }
  return config;
}

// What the worker needs to know about the agent it is, as a module it imports.
// Generated rather than read at runtime because a Worker has no filesystem:
// the manifest's facts are compiled in, and the one thing that is NOT compiled
// in is the charter, which the run fetches from [runtime].repo every time with
// the seat's own token. That split is deliberate — the charter is the thing
// that changes, and an agent reading a stale copy of its own charter is the
// bug the resident runtime avoids by cloning fresh.
export function agentModule(manifest, { source = "agent.toml" } = {}) {
  const rt = manifest.runtime;
  const facts = {
    name: manifest.agent.name,
    description: manifest.agent.description,
    model: rt.model,
    entry: rt.entry,
    repo: rt.repo,
    ref: rt.ref ?? null,
    maxTurns: rt.max_turns ?? 100,
    scopes: manifest.identity.scopes,
    // The ceiling, mapped here by the same SCOPE_MAP every other mint uses,
    // so the token this Worker asks GitHub for can never be wider than the
    // file. Rule 2 holds on the edge because the permissions travel with the
    // bundle instead of being re-derived by something that might disagree.
    permissions: permissionsFor(manifest.identity.scopes),
    cron: manifest.trigger?.cron ?? null,
    webhook: manifest.trigger?.webhook === true,
    routes: routesFor(manifest).map((r) => ({
      name: r.name, model: r.model,
      baseUrl: r.baseUrl, baseUrlEnv: r.baseUrlEnv, tokenEnv: r.tokenEnv,
    })),
    spec: SPEC_VERSION,
    source,
  };
  return `// Generated by \`epito deploy --target cloudflare\` from ${source}.
// Do not edit: change the manifest and deploy again. Nothing here is a secret
// — a manifest is publishable without redaction (spec rule 1) and so is this.
export const AGENT = ${JSON.stringify(facts, null, 2)};
`;
}

// The page an operator reads before they run anything. Not decoration: it is
// where "what do I have to do now" lives, and the deploy's own output is a
// shorter version of it.
export function bundleReadme(manifest, { source = "agent.toml", keyPath = null, notes = [] } = {}) {
  const name = manifest.agent.name;
  const w = workerName(name);
  const secrets = secretNames(manifest);
  const put = (s) => (s.name === BINDINGS.appKey && keyPath
    ? `wrangler secret put ${s.name} < ${keyPath}`
    : `wrangler secret put ${s.name}`);
  return `# ${name} on Cloudflare

Generated by \`epito deploy --target cloudflare\` from \`${source}\`. Everything here
is derived from that one file, and nothing in this directory is a secret.

## What this is

A Worker that is this agent. It has:

- **its own identity** — it signs a JWT as ${name}'s own GitHub App and mints
  its own installation token, scoped to \`${manifest.runtime.repo}\` and to exactly
  the permissions \`[identity].scopes\` maps to. The owner's credentials are
  nowhere in it.
- **a schedule** — ${manifest.trigger?.cron ? `\`${manifest.trigger.cron}\` (UTC), copied verbatim from the manifest into the Worker's triggers.` : "none; this manifest declares no `[trigger].cron`, so it wakes only by hand."}
- **state that survives** — one Durable Object, addressed by the agent's name,
  holding the run log. Redeploying keeps it.
- **a page** — \`GET /\`, showing the agent, its last run${manifest.trigger?.webhook ? ", and a button that triggers it" : " (no button: this manifest does not declare `[trigger].webhook`)"}.

## Deploying it

This is the one step epito does not take for you: it needs your Cloudflare
account, and an agent spending your money is your click, not a tool's. Run
these from this directory.

\`\`\`sh
npx wrangler deploy
${secrets.map((s) => put(s)).join("\n")}
\`\`\`

The secrets, and what each is for:

${secrets.map((s) => `- \`${s.name}\` — ${s.why}`).join("\n")}

\`wrangler deploy\` prints the Worker's URL. The link to send the owner is that
URL with the door key on it:

    https://${w}.<your-subdomain>.workers.dev/?key=<${BINDINGS.door}>

## What an edge run does, exactly

Mints the token, reads \`${manifest.runtime.entry}\` out of \`${manifest.runtime.repo}\`${manifest.runtime.ref ? ` at \`${manifest.runtime.ref}\`` : ""}
with it, asks the model once, records the answer. One turn. It does not clone,
commit or open a pull request — a Worker has no git and no disk, and the page
says so on every run rather than letting this read as the full seat.
${notes.length ? `\n## Before you deploy\n\n${notes.map((n) => `- ${n}`).join("\n")}\n` : ""}`;
}

// The whole bundle, as bytes. One function, so "what does deploy write" has
// one answer and the test suite can assert on all of it at once.
export function cloudflareBundle(manifest, { source = "agent.toml", keyPath = null, compatibilityDate } = {}) {
  const notes = cloudflareNotes(manifest);
  return [
    { path: "wrangler.jsonc", contents: JSON.stringify(wranglerConfig(manifest, { compatibilityDate }), null, 2) + "\n" },
    { path: "agent.js", contents: agentModule(manifest, { source }) },
    { path: "worker.mjs", contents: readFileSync(WORKER_SOURCE, "utf8") },
    { path: "README.md", contents: bundleReadme(manifest, { source, keyPath, notes }) },
  ];
}
